import type { Context } from '@deepseek-ai/cordis';
import type {} from '@deepseek-ai/dsh-api-session-controller';
import type { LlmCallConfig } from '@deepseek-ai/dsh-llm';
import { boundContextSummary, createUserMessage, ReasoningEffortId } from '@deepseek-ai/dsh-llm';
import type { SessionId } from '@deepseek-ai/dsh-session';
import type { SpeedMode } from './settings-types.js';

type Agent = Extract<Awaited<ReturnType<Context['sessionController']['resolveAgent']>>, { agent: unknown }>['agent'];
type Selection = Pick<LlmCallConfig, 'provider' | 'model' | 'reasoningEffort'>;

declare module '@deepseek-ai/cordis' {
  interface Events {
    /** Persist child speed before startup; return rollback for failed startup. @mode bail */
    'codex-subscription/prepare-child-speed'(childId: SessionId, model: string, speedMode: 'standard' | 'fast'): Promise<() => Promise<void>> | undefined;
  }
}

// Live changes require UI confirmation; fresh delegation only prepares its new child's speed.
export function createRunOptions(ctx: Context, settings: {
  get(): Record<string, unknown> & { sessionSpeedModes?: Readonly<Record<string, unknown>> };
  setSessionSpeed(sessionId: string, speedMode: SpeedMode | undefined): Promise<unknown>;
}, supportsFast: (model: string) => boolean) {
  const disposers = new Map<Agent, () => void>();
  const requestSpeeds = new Map<string, SpeedMode>();
  const requestSelections = new Map<string, Selection>();
  const runtimeSelections = new Map<Agent, Selection>();
  const savingSpeeds = new Map<string, SpeedMode>();
  const changing = new Set<string>();
  const speedOf = (id: string): SpeedMode => savingSpeeds.get(id) ?? (settings.get().sessionSpeedModes?.[id] === 'ultrafast' ? 'ultrafast' : settings.get().sessionSpeedModes?.[id] === 'fast' ? 'fast' : 'standard');
  const pendingOf = (agent: Agent): Selection | undefined => {
    const pending = ctx.sessionProjections.stateOf(agent.session, 'modelSelection')?.pending;
    return pending ? { provider: pending.provider, model: pending.model,
      ...(pending.reasoningEffort === undefined ? {} : { reasoningEffort: ReasoningEffortId(pending.reasoningEffort) }),
    } : undefined;
  };

  const attach = (agent: Agent) => {
    if (disposers.has(agent)) return;
    let selected: Selection | undefined;
    let speed: SpeedMode = speedOf(agent.id);
    requestSpeeds.set(agent.id, speed); // A request already past assembly keeps its original speed.
    const dispose = agent.ctx.effect(() => {
      const assembly = agent.ctx.on('system-prompt/assemble', async (_input, _context, next) => {
        const pending = pendingOf(agent);
        const runtime = runtimeSelections.get(agent);
        selected = pending && runtime && pending.provider === runtime.provider && pending.model === runtime.model && pending.reasoningEffort === runtime.reasoningEffort ? pending : undefined;
        if (!selected) runtimeSelections.delete(agent);
        if (selected) requestSelections.set(agent.id, selected); else requestSelections.delete(agent.id);
        speed = speedOf(agent.id);
        const result = await next();
        return selected ? { ...result, variables: { ...result.variables, provider: selected.provider, model: selected.model } } : result;
      }, { prepend: true });
      const request = agent.ctx.on('agent/request', async (_payload, next) => {
        const result = await next();
        requestSpeeds.set(agent.id, speed);
        if (!selected) return result;
        const { reasoningEffort: _effort, ...rest } = result;
        return { ...rest, ...selected };
      }, { prepend: true });
      const notice = agent.ctx.on('agent/pre-step', async ({ messages, step, signal }, next) => {
        const decision = await next();
        const previous = agent.session.requestHeader()?.config;
        if (decision.kind === 'reject' || signal.aborted || !selected || !previous || previous.model === selected.model
          || (decision.messages.length === 0 && (step === 1 || messages.length > 0))) return decision;
        return { ...decision, messages: [...decision.messages, createUserMessage({
          content: [{ type: 'text', text: `[model changed: assistant turns above this point were generated by ${previous.model}; the session continues with ${selected.model}]` }],
          source: { kind: 'model-selection', form: 'notice', summary: boundContextSummary(`${previous.model} → ${selected.model}`) },
        })] };
      }, { prepend: true });
      return () => { assembly(); request(); notice(); disposers.delete(agent); requestSpeeds.delete(agent.id); requestSelections.delete(agent.id); runtimeSelections.delete(agent); savingSpeeds.delete(agent.id); };
    });
    disposers.set(agent, dispose);
  };
  ctx.effect(() => () => { for (const dispose of [...disposers.values()]) dispose(); });
  ctx.effect(() => ctx.on('codex-subscription/prepare-child-speed', async (childId, model, speedMode) => {
    if (speedMode === 'fast' && !supportsFast(model)) throw new Error('Fast is not supported by this Codex model');
    await settings.setSessionSpeed(childId, speedMode);
    return async () => { await settings.setSessionSpeed(childId, undefined); };
  }));

  return {
    selectionFor: (sessionId: string | undefined) => sessionId === undefined ? undefined : requestSelections.get(sessionId),
    // The provider gets the same snapshot as the request config, never a mid-request UI write.
    speedFor: (sessionId: string | undefined) => sessionId === undefined ? undefined : requestSpeeds.get(sessionId) ?? speedOf(sessionId),
    async apply(input: unknown, signal: AbortSignal) {
      if (!input || typeof input !== 'object' || Array.isArray(input)) throw new Error('Invalid run options');
      const value = input as Record<string, unknown>;
      if (Object.keys(value).some(key => !['sessionId', 'model', 'reasoningEffort', 'speedMode', 'expectedModel', 'confirmed'].includes(key))
        || typeof value.sessionId !== 'string' || value.sessionId.length < 1 || value.sessionId.length > 512
        || typeof value.model !== 'string' || value.model.length < 1 || value.model.length > 256
        || typeof value.expectedModel !== 'string' || value.expectedModel.length < 1 || value.expectedModel.length > 256
        || (value.reasoningEffort !== undefined && (typeof value.reasoningEffort !== 'string' || value.reasoningEffort.length < 1 || value.reasoningEffort.length > 64))
        || !['standard', 'fast'].includes(value.speedMode as string) || value.confirmed !== true) throw new Error('Invalid or unconfirmed run options');
      if (settings.get().runtimeOptions === false) throw new Error('Runtime options are disabled');
      const controller = ctx.get('sessionController');
      if (!controller || !ctx.get('sessionProjections')) throw new Error('Runtime options are unavailable on this host');
      const found = await controller.resolveAgent(value.sessionId as SessionId);
      if ('error' in found) throw new Error(found.error.message);
      const agent = found.agent;
      const check = () => {
        signal.throwIfAborted();
        if (settings.get().runtimeOptions === false) throw new Error('Runtime options are disabled');
        if (agent.status !== 'running') throw new Error('This session is no longer running');
        const current = pendingOf(agent) ?? agent.session.requestHeader()?.config;
        if (current?.provider !== 'openai-codex' || current.model !== value.expectedModel) throw new Error('The session model changed. Reopen run options.');
      };
      check();
      if (changing.has(value.sessionId)) throw new Error('A run option change is already being saved');
      changing.add(value.sessionId);
      try {
        const models = await ctx.llm.listModels('openai-codex');
        if (!models.some(model => model.id === value.model)) throw new Error('This model is not in the Codex catalog');
        if (value.speedMode === 'fast' && !supportsFast(value.model)) throw new Error('Fast is not supported by this Codex model');
        const config = await ctx.llm.resolveCallConfig({ provider: 'openai-codex', model: value.model,
          ...(value.reasoningEffort === undefined ? {} : { reasoningEffort: ReasoningEffortId(value.reasoningEffort as string) }),
        }, signal);
        check();
        attach(agent);
        const before = speedOf(agent.id);
        // ponytail: live cross-store fence; use a transaction if crash-atomic selection + Fast is required.
        savingSpeeds.set(agent.id, before);
        let releaseFence = false;
        try {
          await settings.setSessionSpeed(agent.id, value.speedMode as SpeedMode);
          check();
          const selected: Selection = { provider: config.provider, model: config.model,
            ...(config.reasoningEffort === undefined ? {} : { reasoningEffort: config.reasoningEffort }),
          };
          // Existing durable selection + request/header support resume and the shared picker projection.
          // Unlike sessionController.selectModel, this never changes the global default.
          agent.session.append('model/selection', selected);
          runtimeSelections.set(agent, selected);
          releaseFence = true;
          return { selected, speedMode: value.speedMode as SpeedMode, queued: true as const };
        } catch (error) {
          try { await settings.setSessionSpeed(agent.id, before); releaseFence = true; }
          catch { throw new Error('Run option change failed; previous Fast mode could not be restored', { cause: error }); }
          throw error;
        } finally { if (releaseFence) savingSpeeds.delete(agent.id); }
      } finally { changing.delete(value.sessionId); }
    },
  };
}
